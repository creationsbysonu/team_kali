  Future<Ministry> getMyMinistry() async {
    try {
      final responseData = await apiClient.get(ApiEndpoints.myMinistry);

      if (responseData['success'] != true) {
        throw ServerException(
          message: responseData['error'] ?? 'Failed to fetch ministry profile',
        );
      }

      return MinistryModel.fromJson(responseData['data']);
    } on DioException catch (e) {
      throw ServerException(message: _handleDioError(e));
    } catch (e) {
      if (e is ServerException) rethrow;
      throw ServerException(message: e.toString());
    }
  }

  @override
  Future<Ministry> updateMyMinistry({
    String? description,
    String? phone,
    String? address,
    String? website,
    Uint8List? logoBytes,
    String? logoFileName,
  }) async {
    try {
      final formData = FormData.fromMap({
        if (description != null) 'description': description,
        if (phone != null) 'phone': phone,
        if (address != null) 'address': address,
        if (website != null) 'website': website,
        if (logoBytes != null && logoFileName != null)
          'logo': MultipartFile.fromBytes(logoBytes, filename: logoFileName),
      });

      final responseData = await apiClient.patch(
        ApiEndpoints.myMinistry,
        data: formData,
        options: Options(contentType: 'multipart/form-data'),
      );

      if (responseData['success'] != true) {
        throw ServerException(
          message: responseData['error'] ?? 'Failed to update ministry profile',
        );
      }

      return MinistryModel.fromJson(responseData['data']);
    } on DioException catch (e) {
      throw ServerException(message: _handleDioError(e));
    } catch (e) {
      if (e is ServerException) rethrow;
      throw ServerException(message: e.toString());
    }
  }
}
