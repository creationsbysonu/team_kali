      );

      if (responseData['success'] != true) {
        throw ServerException(
          message:
              responseData['error'] ?? 'Failed to fetch deleted ministries',
        );
      }

      final data = responseData['data'] as List<dynamic>? ?? [];
      return data
          .map((json) => MinistryModel.fromJson(json as Map<String, dynamic>))
          .toList();
    } on DioException catch (e) {
      throw ServerException(message: _handleDioError(e));
    } catch (e) {
      if (e is ServerException) rethrow;
      throw ServerException(message: e.toString());
    }
  }

  @override
  Future<Ministry> restoreMinistry(String id) async {
    try {
      final responseData = await apiClient.post(
        ApiEndpoints.adminMinistryRestore(id),
      );

      if (responseData['success'] != true) {
        throw ServerException(
          message: responseData['error'] ?? 'Failed to restore ministry',
        );
      }

      // Handle case where backend doesn't return ministry data
      final data = responseData['data'];
      if (data == null) {
        // Fetch the updated ministry separately
        return await getMinistryById(id);
      }

      return MinistryModel.fromJson(data as Map<String, dynamic>);
    } on DioException catch (e) {
      throw ServerException(message: _handleDioError(e));
    } catch (e) {
      if (e is ServerException) rethrow;
      throw ServerException(message: e.toString());
    }
  }

  @override
  Future<void> hardDeleteMinistry(String id) async {
    try {
      final responseData = await apiClient.post(
        ApiEndpoints.adminMinistryHardDelete(id),
        data: {'confirm': true},
      );

      if (responseData['success'] != true) {
        throw ServerException(
          message:
              responseData['error'] ?? 'Failed to permanently delete ministry',
        );
      }
    } on DioException catch (e) {
      throw ServerException(message: _handleDioError(e));
    } catch (e) {
      if (e is ServerException) rethrow;
      throw ServerException(message: e.toString());
    }
  }

  @override
  Future<void> resetMinistryPassword(String id, String newPassword) async {
    try {
      final responseData = await apiClient.post(
        ApiEndpoints.adminMinistryResetPassword(id),
        data: {'new_password': newPassword},
      );

      if (responseData['success'] != true) {
        throw ServerException(
          message: responseData['error'] ?? 'Failed to reset password',
        );
      }
    } on DioException catch (e) {
      throw ServerException(message: _handleDioError(e));
    } catch (e) {
      if (e is ServerException) rethrow;
      throw ServerException(message: e.toString());
    }
  }

  String _handleDioError(DioException e) {
    if (e.type == DioExceptionType.connectionTimeout) {
      return 'Connection timeout. Please check your internet connection.';
    } else if (e.type == DioExceptionType.receiveTimeout) {
      return 'Server is taking too long to respond. Please try again.';
    } else if (e.type == DioExceptionType.connectionError) {
      return 'Unable to connect to server. Please check your internet.';
    } else if (e.response != null) {
      final statusCode = e.response!.statusCode;
      final data = e.response!.data;

      if (data is Map && data.containsKey('error')) {
        return data['error'].toString();
      }

      switch (statusCode) {
        case 401:
          return 'Unauthorized. Please login again.';
        case 403:
          return 'You do not have permission to perform this action.';
        case 404:
          return 'Resource not found.';
        case 400:
          return 'Invalid request. Please check your inputs.';
        case 500:
          return 'Server error. Please try again later.';
        default:
          return 'Server error ($statusCode). Please try again.';
      }
    }
    return 'Network error. Please check your connection.';
  }

  // ============================================
  // MINISTRY SELF-MANAGEMENT IMPLEMENTATIONS
  // ============================================

